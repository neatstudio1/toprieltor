async function upsertArticle(article) {
  const qs = `filters[slug][$eq]=${encodeURIComponent(article.slug)}`
  const existingBody = await api(`/articles?${qs}&status=draft`)
  const existing = existingBody.data?.[0]

  const payload = {
    title: article.title,
    slug: article.slug,
    excerpt: article.excerpt,
    content: article.content,
    category: article.category,
    tags: [],
    platform: 'blog',
    author_name: 'Яна Чекулова',
    author_role: 'ТОП-риелтор',
    read_minutes: article.read_minutes,
    published_date: article.published_date
  }

  if (existing) {
    const id = existing.documentId ?? existing.id
    await api(`/articles/${id}`, { method: 'PUT', body: JSON.stringify({ data: payload }) })
    return { slug: article.slug, created: false }
  }
  await api('/articles?status=published', { method: 'POST', body: JSON.stringify({ data: payload }) })
  return { slug: article.slug, created: true }
}

