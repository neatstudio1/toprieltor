'use strict'

const STRAPI_URL = process.env.STRAPI_URL || 'http://localhost:1337'
const STRAPI_TOKEN = process.env.STRAPI_IMPORT_TOKEN

if (!STRAPI_TOKEN) {
  console.error('STRAPI_IMPORT_TOKEN не задан. Запустите сначала: npm run bootstrap:strapi -- create-token')
  process.exit(1)
}

async function api(pathname, options = {}) {
  const res = await fetch(`${STRAPI_URL}/api${pathname}`, {
    ...options,
    headers: {
      'Content-Type': 'application/json',
      Authorization: `Bearer ${STRAPI_TOKEN}`,
      ...(options.headers || {})
    }
  })
  const text = await res.text()
  const body = text ? JSON.parse(text) : null
  if (!res.ok) {
    throw new Error(`${options.method || 'GET'} /api${pathname} -> HTTP ${res.status}: ${JSON.stringify(body?.error) || text.slice(0, 300)}`)
  }
  return body
}

