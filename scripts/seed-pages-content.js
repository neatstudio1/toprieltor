const fs = require('fs')
const path = require('path')

const ROOT_ENV_FILE = path.join(__dirname, '..', '.env')
const STRAPI_URL = process.env.STRAPI_URL || 'http://localhost:1337'

function loadToken() {
  if (process.env.STRAPI_IMPORT_TOKEN) return process.env.STRAPI_IMPORT_TOKEN
  const env = fs.readFileSync(ROOT_ENV_FILE, 'utf-8')
  const line = env.split('\n').find((l) => l.startsWith('STRAPI_IMPORT_TOKEN='))
  if (!line) throw new Error('STRAPI_IMPORT_TOKEN не найден в .env — запустите scripts/bootstrap-strapi.js update-token')
  return line.split('=')[1].trim()
}

const TOKEN = loadToken()

async function api(pathname, opts = {}) {
  const res = await fetch(`${STRAPI_URL}/api${pathname}`, {
    ...opts,
    headers: {
      'Content-Type': 'application/json',
      Authorization: `Bearer ${TOKEN}`,
      ...(opts.headers || {})
    }
  })
  const body = await res.json().catch(() => null)
  if (!res.ok) {
    throw new Error(`${opts.method || 'GET'} ${pathname} -> HTTP ${res.status}: ${JSON.stringify(body)}`)
  }
  return body
}

async function fetchAll(pathname, qs = '') {
  const items = []
  let page = 1
  while (true) {
    const sep = qs ? '&' : '?'
    const body = await api(`${pathname}${qs}${sep}pagination[page]=${page}&pagination[pageSize]=100`)
    items.push(...body.data)
    if (page >= body.meta.pagination.pageCount) break
    page += 1
  }
  return items
}

async function upsertBySlug(uid, slug, data) {
  const found = await api(`/${uid}?filters[slug][$eq]=${encodeURIComponent(slug)}`)
  if (found.data[0]) {
    await api(`/${uid}/${found.data[0].documentId}`, {
      method: 'PUT',
      body: JSON.stringify({ data })
    })
    console.log(`  ~ обновлено: ${uid}/${slug}`)
  } else {
    await api(`/${uid}`, {
      method: 'POST',
      body: JSON.stringify({ data: { ...data, publishedAt: new Date().toISOString() } })
    })
    console.log(`  + создано: ${uid}/${slug}`)
  }
}

function fmtRub(n) {
  return Math.round(n).toString().replace(/\B(?=(\d{3})+(?!\d))/g, ' ') + ' ₽'
}

