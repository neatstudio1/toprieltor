async function main() {
  console.log(`Strapi: ${STRAPI_URL}`)

  console.log('\n— district: считаю реальные цифры по каталогу —')
  const projects = await fetchAll('/projects')
  const apartments = await fetchAll('/apartments', '?populate=project')

  console.log('\n— developer —')
  for (const d of DEVELOPERS) {
    await upsertBySlug('developers', d.slug, d)
  }

  console.log('\n— district —')
  for (const d of DISTRICTS) {
    const { keyword, ...rest } = d
    const matchingProjects = projects.filter((p) => (p.district || '').toLowerCase().includes(keyword))
    const slugs = new Set(matchingProjects.map((p) => p.slug))
    const matchingApts = apartments.filter((a) => a.project && slugs.has(a.project.slug) && a.price_from > 0)

    const cheapest = matchingApts.reduce((min, a) => (!min || a.price_from < min.price_from ? a : min), null)
    const pricePerM2 = matchingApts
      .filter((a) => a.area_m2 > 0)
      .map((a) => a.price_from / a.area_m2)
    const avgPricePerM2 = pricePerM2.length ? pricePerM2.reduce((s, v) => s + v, 0) / pricePerM2.length : null
    const deliveryYears = matchingProjects
      .map((p) => p.delivery_date?.match(/(\d{4})/)?.[1])
      .filter(Boolean)
      .map(Number)
    const nearestDelivery = deliveryYears.length ? Math.min(...deliveryYears) : null

    const stats = [
      { label: 'ЖК в продаже', v: String(matchingProjects.length), note: `по данным каталога на ${new Date().toLocaleDateString('ru-RU', { month: 'long', year: 'numeric' })}` },
      cheapest
        ? { label: 'Цена от', v: fmtRub(cheapest.price_from), note: `${cheapest.type} ${cheapest.area_m2.toFixed(1).replace('.', ',')} м²` }
        : { label: 'Цена от', v: '—', note: 'пока нет предложений в каталоге' },
      { label: 'Ближайшая сдача', v: nearestDelivery ? String(nearestDelivery) : '—', note: 'по срокам застройщиков' },
      { label: 'Средняя цена м²', v: avgPricePerM2 ? fmtRub(avgPricePerM2) : '—', note: 'по объектам в продаже' }
    ]

    await upsertBySlug('districts', d.slug, { ...rest, stats })
  }

  console.log('\n— service —')
  const cheapProjects = [...projects]
    .map((p) => {
      const apts = apartments.filter((a) => a.project?.slug === p.slug && a.price_from > 0)
      const min = apts.reduce((m, a) => (!m || a.price_from < m ? a.price_from : m), null)
      return { slug: p.slug, min }
    })
    .filter((p) => p.min)
    .sort((a, b) => a.min - b.min)
  const featuredDefault = cheapProjects.slice(0, 3).map((p) => p.slug)

  for (const s of SERVICES) {
    await upsertBySlug('services', s.slug, { ...s, featured_project_slugs: featuredDefault })
  }

  console.log('\nГотово.')
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
