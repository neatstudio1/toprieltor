/** Все портреты по кругу, начиная с кадра, который выпадает этой странице. */
export function yanaPhotos(seed: string): string[] {
  let hash = 0;
  for (const ch of seed) hash = (hash * 31 + ch.charCodeAt(0)) >>> 0;
  const start = hash % PHOTOS.length;
  return [...PHOTOS.slice(start), ...PHOTOS.slice(0, start)];
}
