/** Нижний регистр, ё→е, «риэлтор»→«риелтор», без города и операторов Директа. */
export function normalizePhrase(raw: string): string {
  return raw
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/риэлтор/g, "риелтор")
    .replace(/[+!"'\[\]()]/g, " ")
    .replace(/(^|\s)(екатеринбург\S*|екб)(?=\s|$)/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function isGroupKey(value: string): value is GroupKey {
  return (GROUP_KEYS as readonly string[]).includes(value);
}

function first(value: string | string[] | undefined): string {
  return (Array.isArray(value) ? value[0] : value) ?? "";
}

export interface PodboryContent extends GroupContent {
  /** Группа для заявки и Метрики; «default», если метки не было. */
  group: GroupKey | "default";
}

export function resolvePodbory(params: {
  utm_content?: string | string[];
  utm_term?: string | string[];
}): PodboryContent {
  const content = first(params.utm_content).trim().toLowerCase();
  const phrase = normalizePhrase(first(params.utm_term));

  let group: GroupKey | undefined = isGroupKey(content) ? content : undefined;
  if (!group && phrase) group = PHRASE_GROUPS[phrase];

  const base = GROUPS[group ?? DEFAULT_GROUP];
  const override = phrase ? PHRASE_OVERRIDES[phrase] : undefined;
  return { ...base, h1: override ?? base.h1, group: group ?? "default" };
}

